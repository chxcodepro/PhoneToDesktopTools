// Package blank 黑屏（隐私屏）：手机连着控制电脑时，让电脑的显示器显示黑屏，旁边的人看不到在操作什么，
// 手机上的虚拟桌面照常能看到画面、照常操作（和向日葵的「黑屏模式」、UU 远程的「防窥模式」一样）。
//
// Windows 10 2004 起：每个显示器上盖一个全屏的黑色窗口，置顶、鼠标点击穿透、不抢焦点，
// 并用 SetWindowDisplayAffinity(WDA_EXCLUDEFROMCAPTURE) 把它排除在截屏之外——显示器上看得到，截屏里看不到。
// 更早的 Windows 上这个标志会退化成「截屏里也是黑的」，手机上就什么也看不到了，所以不支持。
// 银河麒麟（X11）、Mac 暂不支持：X11 没有把窗口排除在截屏外的办法。
package blank

// Text 黑屏上显示的说明（两行），免得旁边的人以为电脑坏了去关机
var Text = [2]string{
	"这台电脑正在被手机远程控制，屏幕已暂时关闭",
	"断开连接后自动恢复显示，也可以按 Ctrl+Alt+Q 断开",
}
